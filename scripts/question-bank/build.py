#!/usr/bin/env python3
"""Checks the hand-written question bank and writes a SQL migration.

Usage: python3 scripts/question-bank/build.py <output.sql> <file.json> [file.json ...]
Each file maps skill id -> questions: d (difficulty), p (passage), s (stem, optional),
r (right answer), w (three wrong answers), e (explanation). Answer letters are assigned
here so they stay balanced across A-D.
"""
import base64, json, random, re, sys, textwrap
from collections import Counter

STEMS = {
    "words_in_context": "Which choice completes the text with the most logical and precise word or phrase?",
    "central_ideas": "Which choice best states the main idea of the text?",
    "inferences": "Which choice most logically completes the text?",
    "boundaries": "Which choice completes the text so that it conforms to the conventions of Standard English?",
    "form_structure_sense": "Which choice completes the text so that it conforms to the conventions of Standard English?",
    "transitions": "Which choice completes the text with the most logical transition?",
}
MAX_WORDS = {"easy": 90, "medium": 130, "hard": 160}

out_path, files = sys.argv[1], sys.argv[2:]
items = []
for f in files:
    for skill, questions in json.load(open(f)).items():
        items += [(skill, q) for q in questions]

seen, problems = set(), []
for skill, q in items:
    label = f"{skill}: {q['p'][:50]!r}"
    choices = [q["r"].strip()] + [w.strip() for w in q["w"]]
    if q["d"] not in MAX_WORDS: problems.append(f"bad difficulty {label}")
    if len(choices) != 4 or len(set(c.lower() for c in choices)) != 4: problems.append(f"choices {label}")
    if not all(choices): problems.append(f"empty choice {label}")
    if not (q.get("s") or STEMS.get(skill)): problems.append(f"no stem {label}")
    if len(q["e"]) < 30: problems.append(f"short explanation {label}")
    if len(q["p"].split()) > MAX_WORDS[q["d"]]: problems.append(f"too long ({len(q['p'].split())}) {label}")
    if q["p"] in seen: problems.append(f"duplicate {label}")
    seen.add(q["p"])
    if re.search(r"\\(frac|sqrt)", q["p"]): problems.append(f"LaTeX {label}")
    # A choice after a blank must not create a capitalization clash.
    if skill == "boundaries" and q["r"].rstrip().endswith(".") and re.search(r"______ [a-z]", q["p"]): problems.append(f"period before lowercase {label}")
if problems:
    sys.exit("\n".join(problems))

positions = [0, 1, 2, 3] * (len(items) // 4 + 1)
random.Random("sat-sprint").shuffle(positions)
rows = []
for i, (skill, q) in enumerate(items):
    wrong = [w.strip() for w in q["w"]]
    random.Random(q["p"]).shuffle(wrong)
    wrong.insert(positions[i], q["r"].strip())
    rows.append({
        "skill_id": skill, "difficulty": q["d"], "passage": q["p"], "stem": q.get("s") or STEMS[skill],
        "choices": wrong, "answer": "ABCD"[positions[i]], "explanation": q["e"],
    })

# The questions travel as base64 JSON: the Supabase SQL editor misread ordinary sentences
# ("harden into judgment") as SQL. The not-exists check makes the file safe to run twice.
encoded = base64.b64encode(json.dumps(rows, ensure_ascii=False).encode()).decode()
wrapped = "\n".join(textwrap.wrap(encoded, 120))
open(out_path, "w").write(f"""-- Hand-written Reading and Writing questions for timed modules.
-- Generated by scripts/question-bank/build.py from scripts/question-bank/*.json.
insert into public.questions (skill_id, difficulty, passage, stem, choices, answer, explanation, model)
select q.skill_id, q.difficulty, q.passage, q.stem, q.choices, q.answer, q.explanation, 'hand-written'
from jsonb_to_recordset(convert_from(decode('
{wrapped}
', 'base64'), 'UTF8')::jsonb) as q(skill_id text, difficulty text, passage text, stem text, choices jsonb, answer text, explanation text)
where not exists (select 1 from public.questions x where x.passage = q.passage and x.stem = q.stem);
""")

print(len(items), "questions")
print("difficulty", dict(Counter(q["d"] for _, q in items)))
print("per skill", dict(Counter(s for s, _ in items)))
print("answers", dict(sorted(Counter("ABCD"[positions[i]] for i in range(len(items))).items())))
for d in MAX_WORDS:
    w = [len(q["p"].split()) for _, q in items if q["d"] == d and "•" not in q["p"]]
    print(d, "passage words avg", round(sum(w) / len(w)), "max", max(w))
